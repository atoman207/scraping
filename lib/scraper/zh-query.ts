/** 照合の効率と正しさのため、長い語から順に見る(複合語を先に取るため) */
const KEYS_BY_LENGTH = Object.keys(JA_ZH).sort((a, b) => b.length - a.length);

/** 漢字(CJK統合漢字)だけでできた語か */
function isKanjiOnly(s: string): boolean {
  return /^[一-鿿]{2,}$/.test(s);
}

export type ChineseQuery = {
  /** 1688 に投げる中国語。作れなかったときは空文字 */
  query: string;
  /** 訳せた語(「スマホ → 手机」の形。画面とログに出して確認できるようにする) */
  matched: string[];
  /** 訳せなかった語。対訳表に足す候補になる */
  unmatched: string[];
  /**
   * 対訳表で1語以上訳せたか。
   * false のときは漢字をそのまま使った当て推量なので、画面でもその旨を出す。
   */
  confident: boolean;
};

/**
 * 日本語タイトルから 1688 用の中国語検索語を作る。
 *
 * 1. 売り文句と記号を落とす
 * 2. 対訳表を長い語から照合して、中国語に置き換える
 * 3. 4語まで採用(多すぎると1688側で0件になる)
 * 4. 1語も訳せなければ、漢字語をそのまま使う(confident=false)
 */
export function toChineseQuery(title: string, maxTerms = 4): ChineseQuery {
  const cleaned = title
    .replace(SYMBOLS, " ")
    .replace(NOISE, " ")
    .replace(/\s+/g, " ")
    .trim();
  const lower = cleaned.toLowerCase();

  // 照合済みの範囲を伏せ字にして、同じ文字を二重に拾わないようにする。
  // 伏せ字は同じ長さの空白に置き換えるので、位置(at)は元の文字列と同じまま使える。
  let rest = lower;
  const hits: { at: number; ja: string; zh: string }[] = [];

  // 途中で打ち切らず、**訳せる語はすべて**拾う。
  // 打ち切ると、その先にある語が「訳せなかった語」に混ざってしまい、
  // 対訳表を育てるときの手がかり(unmatched)が当てにならなくなるため。
  for (const key of KEYS_BY_LENGTH) {
    const at = rest.indexOf(key.toLowerCase());
    if (at < 0) continue;
    const value = JA_ZH[key];
    if (!hits.some((h) => h.zh === value)) hits.push({ at, ja: key, zh: value });
    rest = rest.slice(0, at) + " ".repeat(key.length) + rest.slice(at + key.length);
  }

  // 採用するのは maxTerms 語まで(多すぎると1688側で0件になる)。
  // どれを残すかは **元の語が長い順**。長い語ほど商品そのものを指していて、
  // 色や数量のような付随的な語より手がかりになる
  // (「ホワイト」より「カジュアルパンツ」を残したい)。
  const picked = [...hits].sort((a, b) => b.ja.length - a.ja.length).slice(0, maxTerms);

  // 並びは元のタイトルに現れた順に戻す。中国語も語順で読みが変わるため
  // (「ペット ハーネス」が「胸背带 宠物」になると不自然)。
  picked.sort((a, b) => a.at - b.at);
  const zh = picked.map((h) => h.zh);
  const matched = picked.map((h) => `${h.ja} → ${h.zh}`);

  // 残った語(=訳せなかった語)。対訳表を育てるための手がかりとして返す
  const unmatched = rest
    .split(/[\s　]+/)
    .map((t) => t.trim())
    .filter((t) => t.length >= 2);

  if (zh.length) {
    return { query: zh.join(" "), matched, unmatched, confident: true };
  }

  // 1語も訳せなかったときだけ、漢字語をそのまま使う。
  // 新字体と簡体字の違いで外れることがあるので confident=false を立てる。
  const kanji = cleaned
    .split(/[\s　]+/)
    .map((t) => t.trim())
    .filter(isKanjiOnly)
    .slice(0, maxTerms);

  return {
    query: kanji.join(" "),
    matched: [],
    unmatched,
    confident: false,
  };
}
