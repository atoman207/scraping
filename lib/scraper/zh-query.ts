/**
 * 日本語の商品タイトルから、1688(中国)で使える検索語を作る。
 *
 * ■ なぜ必要か
 *   1688 は中国国内向けの卸売サイトで、商品タイトルはすべて中国語(簡体字)。
 *   日本語のキーワードをそのまま投げても1件も当たらない。
 *   これまで `keywords=<日本語>` のリンクを出していたので、
 *   ログインして開いても結果が出ない状態だった。
 *
 * ■ なぜ機械翻訳APIを使わないか
 *   DeepL/Google いずれも鍵が要る。鍵無しで使える非公式の翻訳エンドポイントは
 *   規約が曖昧で、商用サービスの土台にはできない。
 *   そこで **中国輸入でよく出る語だけを収めた対訳表** を持つ。
 *   語彙は限られるが、外部に依存せず、結果が毎回同じで、
 *   外れたときに何が外れたのかが分かる(matched / unmatched を返す)。
 *
 * ■ 漢字をそのまま通さない理由
 *   日本語は新字体、中国語は簡体字で、見た目が同じでも別字のことが多い。
 *   「収納」は中国語では「收纳」で、収≠收 / 納≠纳。そのまま投げても当たらない。
 *   そのため **対訳表に載っている語だけを訳す** のが基本で、
 *   1語も訳せなかったときに限って漢字語をそのまま使う(confident=false で印を付ける)。
 *
 * ■ 語彙を足すには
 *   JA_ZH に1行足すだけ。長い語から順に照合するので、
 *   「スマホスタンド」のような複合語を先に入れておけば、そちらが優先される。
 *   `npm run test:zh` で、いまDBにある商品タイトルに対する訳せ具合を確認できる。
 */

